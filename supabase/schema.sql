-- Safe to re-run: policies and triggers are recreated idempotently.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now()
);

create table if not exists public.watchlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ticker text not null,
  created_at timestamptz not null default now(),
  unique(user_id, ticker)
);

create table if not exists public.research_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ticker text not null,
  title text not null default '',
  body text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists watchlists_user_created_idx on public.watchlists(user_id, created_at desc);
create index if not exists research_notes_user_updated_idx on public.research_notes(user_id, updated_at desc);

alter table public.profiles enable row level security;
alter table public.watchlists enable row level security;
alter table public.research_notes enable row level security;

drop policy if exists "profile owner can read" on public.profiles;
drop policy if exists "profile owner can insert" on public.profiles;
drop policy if exists "profile owner can update" on public.profiles;
drop policy if exists "watchlist owner all" on public.watchlists;
drop policy if exists "notes owner all" on public.research_notes;

create policy "profile owner can read" on public.profiles for select using (auth.uid() = id);
create policy "profile owner can insert" on public.profiles for insert with check (auth.uid() = id);
create policy "profile owner can update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "watchlist owner all" on public.watchlists for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "notes owner all" on public.research_notes for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, new.raw_user_meta_data ->> 'display_name')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists research_notes_updated_at on public.research_notes;
create trigger research_notes_updated_at
before update on public.research_notes
for each row execute procedure public.set_updated_at();
