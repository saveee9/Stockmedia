-- Stockpedia schema for Supabase. Run in SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now()
);
create table if not exists public.watchlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ticker text not null,
  created_at timestamptz not null default now(),
  unique(user_id, ticker)
);
create table if not exists public.research_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ticker text not null,
  title text not null default '',
  body text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
alter table public.watchlists enable row level security;
alter table public.research_notes enable row level security;
create policy "profile owner can read" on public.profiles for select using (auth.uid() = id);
create policy "profile owner can insert" on public.profiles for insert with check (auth.uid() = id);
create policy "profile owner can update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "watchlist owner all" on public.watchlists for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "notes owner all" on public.research_notes for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name) values (new.id, new.raw_user_meta_data ->> 'display_name');
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
